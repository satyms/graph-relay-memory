"""
High-performance OpenAI-compatible local server using openvino-genai for Windows.
Serves Qwen2.5-7B-Instruct INT4 with chat template and tool calling support.
"""
import argparse
import json
import logging
import re
import time
from typing import Any, Dict, List, Optional
import openvino_genai as ov_genai
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
import uvicorn

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger("openvino_server")

app = FastAPI(title="OpenVINO Qwen2.5 OpenAI-compatible API")

pipeline: Optional[ov_genai.LLMPipeline] = None
model_id: str = "Qwen/Qwen2.5-7B-Instruct"


class Message(BaseModel):
    role: str
    content: Optional[str] = ""


class ChatCompletionRequest(BaseModel):
    model: Optional[str] = None
    messages: List[Message]
    tools: Optional[List[Dict[str, Any]]] = None
    tool_choice: Optional[Any] = "auto"
    temperature: Optional[float] = 0.1
    max_tokens: Optional[int] = 512


def build_qwen_chat_prompt(messages: List[Message], tools: Optional[List[Dict[str, Any]]] = None) -> str:
    """
    Constructs ChatML format with Qwen-specific tool definitions.
    """
    prompt = ""
    system_rendered = False

    for m in messages:
        if m.role == "system":
            system_content = m.content or ""
            if tools:
                tools_json = json.dumps([t.get("function", t) for t in tools], indent=2)
                system_content += f"\n\n# Tools\n\nYou may call one or more functions to assist with the user query.\nYou are provided with function signatures within <tools></tools> XML tags:\n<tools>\n{tools_json}\n</tools>\n\nFor each function call, return a json object with function name and arguments within <tool_call></tool_call> XML tags:\n<tool_call>\n{{\"name\": <function-name>, \"arguments\": <args-json-object>}}\n</tool_call>"
            prompt += f"<|im_start|>system\n{system_content}<|im_end|>\n"
            system_rendered = True
        else:
            prompt += f"<|im_start|>{m.role}\n{m.content or ''}<|im_end|>\n"

    if not system_rendered and tools:
        tools_json = json.dumps([t.get("function", t) for t in tools], indent=2)
        system_content = f"# Tools\n\nYou may call one or more functions to assist with the user query.\nYou are provided with function signatures within <tools></tools> XML tags:\n<tools>\n{tools_json}\n</tools>\n\nFor each function call, return a json object with function name and arguments within <tool_call></tool_call> XML tags:\n<tool_call>\n{{\"name\": <function-name>, \"arguments\": <args-json-object>}}\n</tool_call>"
        prompt = f"<|im_start|>system\n{system_content}<|im_end|>\n" + prompt

    prompt += "<|im_start|>assistant\n"
    return prompt


def parse_tool_calls(text: str) -> List[Dict[str, Any]]:
    """
    Parses <tool_call> JSON blocks generated by Qwen2.5.
    """
    tool_calls = []
    # Match <tool_call>...</tool_call>
    matches = re.findall(r"<tool_call>\s*(\{.*?\})\s*</tool_call>", text, re.DOTALL)
    for idx, raw in enumerate(matches):
        try:
            parsed = json.loads(raw)
            name = parsed.get("name")
            args = parsed.get("arguments", {})
            if name:
                tool_calls.append({
                    "id": f"call_ov_{idx}_{int(time.time()*1000)%10000}",
                    "type": "function",
                    "function": {
                        "name": name,
                        "arguments": json.dumps(args) if isinstance(args, dict) else str(args)
                    }
                })
        except Exception:
            continue
    return tool_calls


@app.get("/health")
def health():
    return {"status": "ok", "model": model_id}


@app.get("/v1/models")
def list_models():
    return {
        "object": "list",
        "data": [{
            "id": model_id,
            "object": "model",
            "created": int(time.time()),
            "owned_by": "openvino"
        }]
    }


import threading
pipeline_lock = threading.Lock()

@app.post("/v1/chat/completions")
def chat_completions(req: ChatCompletionRequest):
    global pipeline
    if pipeline is None:
        raise HTTPException(status_code=503, detail="OpenVINO pipeline not initialized")

    prompt = build_qwen_chat_prompt(req.messages, req.tools)

    config = ov_genai.GenerationConfig()
    config.max_new_tokens = req.max_tokens or 512
    config.temperature = req.temperature or 0.1

    with pipeline_lock:
        raw_output = pipeline.generate(prompt, config)

    # Check for tool calls in response
    tool_calls = parse_tool_calls(raw_output)
    clean_content = re.sub(r"<tool_call>.*?</tool_call>", "", raw_output, flags=re.DOTALL).strip()

    message_payload: Dict[str, Any] = {
        "role": "assistant",
        "content": clean_content
    }
    if tool_calls:
        message_payload["tool_calls"] = tool_calls

    finish_reason = "tool_calls" if tool_calls else "stop"

    return {
        "id": f"chatcmpl-ov-{int(time.time())}",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": req.model or model_id,
        "choices": [{
            "index": 0,
            "message": message_payload,
            "finish_reason": finish_reason
        }],
        "usage": {
            "prompt_tokens": len(prompt.split()),
            "completion_tokens": len(raw_output.split()),
            "total_tokens": len(prompt.split()) + len(raw_output.split())
        }
    }


def main():
    global pipeline, model_id
    parser = argparse.ArgumentParser(description="OpenVINO Qwen2.5 OpenAI-compatible API Server")
    parser.add_argument("--model-path", default="models/qwen2.5-7b-int4", help="Path to exported OpenVINO model")
    parser.add_argument("--device", default="CPU", help="Target OpenVINO device: CPU, GPU, etc.")
    parser.add_argument("--port", type=int, default=8000, help="Port to listen on")
    parser.add_argument("--host", default="127.0.0.1", help="Host address")
    args = parser.parse_args()

    model_id = "Qwen/Qwen2.5-7B-Instruct"
    log.info("Loading OpenVINO model from '%s' onto device '%s'...", args.model_path, args.device)
    pipeline = ov_genai.LLMPipeline(args.model_path, args.device)
    log.info("✓ Model loaded successfully. Starting API server at http://%s:%d/v1", args.host, args.port)

    uvicorn.run(app, host=args.host, port=args.port, log_level="warning")


if __name__ == "__main__":
    main()
